/** Month names as CLDR/ICU renders them in English. */
const MONTH_NAMES = [
  'Muharram', 'Safar', 'Rabiʻ I', 'Rabiʻ II', 'Jumada I', 'Jumada II',
  'Rajab', 'Shaʻban', 'Ramadan', 'Shawwal', 'Dhuʻl-Qiʻdah', 'Dhuʻl-Hijjah',
];

/** Chronological Julian Day Number (midnight-based) for a Gregorian date. */
function cjdnFromGregorian(year, month, day) { // month 1–12
  let m = month;
  let y = year;
  if (m < 3) { y -= 1; m += 12; }
  const a = Math.floor(y / 100);
  const jgc = a - Math.floor(a / 4) - 2;
  return Math.floor(365.25 * (y + 4716)) + Math.floor(30.6001 * (m + 1)) + day - jgc - 1524;
}

/**
 * Convert a Gregorian date to Umm al-Qura { day, month, year } (1-indexed).
 * Returns null outside the table's valid range (1356–1500 AH).
 */
export function hijriFromGregorian(year, month, day) {
  const mcjdn = cjdnFromGregorian(year, month, day) - 2400000;
  let i = 0;
  while (i < ummalqura.length && ummalqura[i] <= mcjdn) i += 1;
  if (i === 0 || i >= ummalqura.length) return null;

  const lunation = i + 16258;
  const hijriYear = Math.floor((lunation - 1) / 12) + 1;
  const hijriMonth = lunation - 12 * Math.floor((lunation - 1) / 12);
  const hijriDay = mcjdn - ummalqura[i - 1] + 1;
  return { day: hijriDay, month: hijriMonth, year: hijriYear };
}

/**
 * "Rabiʻ I 10, 1448 AH" — with the era included, so callers must not append
 * "AH" themselves. Returns null for dates outside the valid range.
 */
export function formatHijriDate(date) {
  const h = hijriFromGregorian(date.getFullYear(), date.getMonth() + 1, date.getDate());
  if (!h) return null;
  return `${MONTH_NAMES[h.month - 1]} ${h.day}, ${h.year} AH`;
}
